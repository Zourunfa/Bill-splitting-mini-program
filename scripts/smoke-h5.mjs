  await page.reload(); await page.waitForTimeout(650);
  assert.equal(await input('0.00').inputValue(), '', '重新加载不能恢复未提交金额');
  await input('0.00').fill('10.01');
  await input('比如：康定住宿、午饭、加油').fill('路边的热咖啡');
