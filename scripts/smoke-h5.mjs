  const bill = trips[0].expenses.find(e => e.title === '路边的热咖啡');
  assert.equal(bill.amount, 1001); assert.equal(bill.participantIds.length, 3);
  assert.equal(Object.values(bill.shares).reduce((a, b) => a + b, 0), 1001);
  await click('路边的热咖啡');
  await input('0.00').fill('12.01'); await click('保存修改');
  trips = await snapshot(); assert.equal(trips[0].expenses.find(e => e.id === bill.id).amount, 1201);
  // 编辑过程中其他成员改名，仍应保存；同一笔账单被改动则保留当前页输入并要求核对。
