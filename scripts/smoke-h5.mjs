  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390, '移动端页面不能横向溢出');
  await page.evaluate(() => localStorage.setItem('jiqian_draft_demo_trip_demo_me_new', JSON.stringify({ data: { amount: '10.5雅江', title: '旧缓存内容' } })));
  await click('＋ 记一笔共同开销');
  assert.equal(await input('0.00').inputValue(), '', '旧版草稿不能恢复到新表单');
  await input('0.00').fill('10.01');
