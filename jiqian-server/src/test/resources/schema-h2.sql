CREATE TABLE users (
  id VARCHAR(64) PRIMARY KEY,
  name VARCHAR(20) NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE TABLE trips (
  id VARCHAR(64) PRIMARY KEY,
  name VARCHAR(30) NOT NULL,
  destination VARCHAR(30) NOT NULL,
  start_date CHAR(10) NOT NULL,
  end_date CHAR(10) NOT NULL,
  creator_id VARCHAR(64) NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'active',
  invite_code VARCHAR(64) NOT NULL UNIQUE,
  version INT NOT NULL DEFAULT 1,
  created_at BIGINT NOT NULL,
  FOREIGN KEY (creator_id) REFERENCES users(id)
);
CREATE TABLE trip_members (
  trip_id VARCHAR(64) NOT NULL,
  member_id VARCHAR(64) NOT NULL,
  name VARCHAR(20) NOT NULL,
  color VARCHAR(10) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  member_order INT NOT NULL,
  joined_at BIGINT NOT NULL,
  PRIMARY KEY (trip_id, member_id),
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE,
  FOREIGN KEY (member_id) REFERENCES users(id)
);
CREATE TABLE expenses (
  trip_id VARCHAR(64) NOT NULL,
  id VARCHAR(100) NOT NULL,
  title VARCHAR(60) NOT NULL,
  amount INT NOT NULL,
  payer_id VARCHAR(64) NOT NULL,
  category VARCHAR(10) NOT NULL,
  expense_date CHAR(10) NOT NULL,
  note VARCHAR(200) NOT NULL DEFAULT '',
  creator_id VARCHAR(64) NOT NULL,
  deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (trip_id, id),
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE,
  FOREIGN KEY (payer_id) REFERENCES users(id),
  FOREIGN KEY (creator_id) REFERENCES users(id)
);
CREATE TABLE expense_shares (
  trip_id VARCHAR(64) NOT NULL,
  expense_id VARCHAR(100) NOT NULL,
  member_id VARCHAR(64) NOT NULL,
  amount INT NOT NULL,
  participant_order INT NOT NULL,
  PRIMARY KEY (trip_id, expense_id, member_id),
  FOREIGN KEY (trip_id, expense_id) REFERENCES expenses(trip_id, id) ON DELETE CASCADE,
  FOREIGN KEY (member_id) REFERENCES users(id)
);
CREATE TABLE settlements (
  trip_id VARCHAR(64) NOT NULL,
  id VARCHAR(100) NOT NULL,
  from_id VARCHAR(64) NOT NULL,
  to_id VARCHAR(64) NOT NULL,
  amount INT NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'pending',
  created_at BIGINT NOT NULL,
  confirmed_at BIGINT,
  PRIMARY KEY (trip_id, id),
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE,
  FOREIGN KEY (from_id) REFERENCES users(id),
  FOREIGN KEY (to_id) REFERENCES users(id)
);
CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id VARCHAR(64) NOT NULL,
  actor_id VARCHAR(64) NOT NULL,
  action VARCHAR(20) NOT NULL,
  target_id VARCHAR(100) NOT NULL,
  at BIGINT NOT NULL,
  FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE,
  FOREIGN KEY (actor_id) REFERENCES users(id)
);
